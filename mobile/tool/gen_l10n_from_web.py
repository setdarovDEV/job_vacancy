def key(section, k):
    camel = re.sub(r"_(\w)", lambda m: m.group(1).upper(), k)  # internal_error -> internalError
    return section + camel[0].upper() + camel[1:]


def to_icu(s):
    names = re.findall(r"\{\{(\w+)\}\}", s)
    return re.sub(r"\{\{(\w+)\}\}", r"{\1}", s), names


def flatten(d):
    out = {}
    for sec in SECTIONS:
        for k, v in d[sec].items():
            if isinstance(v, str):
                out[key(sec, k)] = v
    return out


msgs = {l: json.load(open(os.path.join(SRC, f"{l}.json"), encoding="utf-8")) for l in LOCALES}
arb_dir = os.path.join(ROOT, "lib/core/l10n/arb")
os.makedirs(arb_dir, exist_ok=True)
for l, suffix in LOCALES.items():
    flat = flatten(msgs[l])
    for k, per in MOBILE.items():
        flat["app" + k[0].upper() + k[1:]] = per[l]
    arb = {"@@locale": suffix}
    for k in sorted(flat):
        text, names = to_icu(flat[k])
        arb[k] = text
        if l == "uz" and names:
            arb["@" + k] = {"placeholders": {n: {"type": "String"} for n in names}}
    with open(os.path.join(arb_dir, f"app_{suffix}.arb"), "w", encoding="utf-8") as f:
        json.dump(arb, f, ensure_ascii=False, indent=2)
        f.write("\n")


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


